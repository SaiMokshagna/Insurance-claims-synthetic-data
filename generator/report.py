"""Validation summary (markdown) and the machine-readable results file."""
from pathlib import Path

import pandas as pd

from generator.anomalies import EXPECTED_FAILURES, MAY_ALSO_FAIL
from generator.config import REFERENCE_DATE

# Grouping is by keywords in the check name (first match wins); it is a reading aid only.
FAMILIES = [
    ("Primary-key uniqueness", ["is unique"]),
    ("ID format", ["matches id format"]),
    ("Duplicate checks", ["at most one", "at most once", "duplicate"]),
    ("Foreign keys and joins", ["fk ", "belongs to", "is attached", "assigned to the claim",
                                "points to an existing", "exists in its table", "embeds its claim_id",
                                "product matches", "reviewer differs", "product in policy_id",
                                "claim_type equals"]),
    ("Allowed values", ["allowed values", "codes are allowed", "allowed for the claim type",
                        "triggered exclusion"]),
    ("Lifecycle and audit trail", ["transition", "from_status", " last ", "released",
                                   "supersedes", "closed claims"]),
    ("Arithmetic reconciliation", ["equals", "sum of", "follows deductible", "do not exceed",
                                   "recount", "re-derivation", "<= claimed_amount", "authority covers",
                                   "limit_applied", "deductible <", "0 <= reserve", "reporting_delay"]),
    ("Date ordering", ["date", " age ", "inside", "within", "between"]),
]


def categorize(check):
    name = check.lower()
    for family, keywords in FAMILIES:
        if any(k in name for k in keywords):
            return family
    return "Business rules"


def _md_table(df):
    cols = list(df.columns)
    lines = ["| " + " | ".join(str(c) for c in cols) + " |",
             "|" + "|".join("---" for _ in cols) + "|"]
    for row in df.itertuples(index=False):
        lines.append("| " + " | ".join("" if pd.isna(v) else str(v) for v in row) + " |")
    return "\n".join(lines)


def _counts(series, name):
    c = series.value_counts().sort_index()
    return pd.DataFrame({name: c.index, "Rows": c.values,
                         "Share": [f"{v / c.sum():.1%}" for v in c.values]})


def _quantiles(series, name, money=False):
    q = series.quantile([0, 0.25, 0.5, 0.75, 0.95, 1.0])
    fmt = (lambda v: f"{v:,.2f}") if money else (lambda v: f"{v:,.0f}")
    return pd.DataFrame({"Statistic": ["min", "25%", "median", "75%", "95%", "max"],
                         name: [fmt(v) for v in q.values]})


def family_table(results):
    totals = {}
    for r in results:
        passed, total = totals.get(categorize(r["check"]), (0, 0))
        totals[categorize(r["check"])] = (passed + int(r["passed"]), total + 1)
    return pd.DataFrame([{"Check family": f, "Checks": t, "Passed": p}
                         for f, (p, t) in sorted(totals.items())])


def defect_table(results, gt):
    injected = gt[gt["origin"] == "INJECTED"]["issue_type"].value_counts().to_dict()
    rows = []
    for r in results:
        if r["passed"]:
            continue
        name = r["check"]
        if name in EXPECTED_FAILURES:
            issues = EXPECTED_FAILURES[name]
            expected = str(sum(injected.get(i, 0) for i in issues))
        elif name in MAY_ALSO_FAIL:
            issues = [MAY_ALSO_FAIL[name]]
            expected = f"up to {injected.get(issues[0], 0)}"
        else:
            issues, expected = [], "0"
        rows.append({"Failing check": name, "Bad rows": r["bad_rows"], "Expected": expected,
                     "Explained by": ", ".join(issues) or "NOT EXPLAINED"})
    return pd.DataFrame(rows, columns=["Failing check", "Bad rows", "Expected", "Explained by"])


def build_report(run, final, gt, clean_results, final_results, problems, scores, mismatches):
    claims = final["claims"]
    out = []
    add = out.append

    add("# Validation Summary")
    add("")
    add(f"Generated by `python -m generator --seed {run['seed']} --policies {run['policies']} "
        f"--claims {run['claims']}`. Reference date: {REFERENCE_DATE}. All data is synthetic.")
    add("")

    add("## 1. Dataset")
    add("")
    rows = [{"Table": name, "Rows": len(df)} for name, df in final.items()]
    rows.append({"Table": "ground_truth (separate file)", "Rows": len(gt)})
    add(_md_table(pd.DataFrame(rows)))
    add("")

    n_ok = sum(r["passed"] for r in clean_results)
    add("## 2. Validation of the clean dataset")
    add("")
    add(f"**{n_ok}/{len(clean_results)} checks passed** on the clean dataset, before the Layer B "
        "defects were injected. Checks cover key uniqueness, ID formats, foreign keys, allowed "
        "values, date ordering, arithmetic reconciliation, lifecycle transitions and duplicates.")
    add("")
    add(_md_table(family_table(clean_results)))
    add("")

    add("## 3. Injected defects and the checks that catch them")
    add("")
    add("After the Layer B defects are injected the same checks run again. Every check that fails "
        "must match a number of injected defects; a failure with no matching label is a bug.")
    add("")
    add(_md_table(defect_table(final_results, gt)))
    add("")
    if problems:
        add("**Problems found:**")
        add("")
        for p in problems:
            add(f"- {p}")
    else:
        add("**Result:** every failing check is explained by the ground truth, and no unrelated "
            "row was changed.")
    add("")

    add("## 4. Ground truth")
    add("")
    add("`ground_truth.csv` has one row per claim. `INJECTED` rows were created deliberately; "
        "`NATURAL` rows arose in the baseline and were handled correctly by the workflow; "
        "`NONE` rows have no issue. Expected decisions come from the rules engine, not from a "
        "hand-written list.")
    add("")
    labels = gt.groupby(["origin", "issue_type"]).size().reset_index(name="Claims")
    add(_md_table(labels.rename(columns={"origin": "Origin", "issue_type": "Issue type"})))
    add("")
    add(_md_table(_counts(gt["expected_decision"], "Expected decision")))
    add("")

    add("## 5. Detection run scored against the ground truth")
    add("")
    add("A rules-based detector reads only the final tables (never `ground_truth.csv`) and predicts "
        "one issue per claim. Defect types are detected with independent pandas logic, so a "
        "perfect score shows the injected defects are detectable from the recorded data. The "
        "three natural types (fraud, incomplete evidence, over-limit) use the documented rules "
        "engine, so for those the score shows only that labels and rules agree. The table is a "
        "benchmark harness: any other model's predictions can be scored the same way.")
    add("")
    table = scores.copy()
    for col in ("precision", "recall", "f1"):
        table[col] = table[col].map(lambda v: "n/a" if pd.isna(v) else f"{v:.3f}")
    add(_md_table(table.rename(columns={"issue_type": "Issue type"})))
    add("")
    add(f"Misclassified claims: **{len(mismatches)}** of {len(gt)}.")
    add("")

    add("## 6. Distributions")
    add("")
    add(_md_table(_counts(claims["claim_type"], "Claim type")))
    add("")
    add(_md_table(_counts(final["policies"]["status"], "Policy status")))
    add("")
    add(_md_table(_counts(claims["current_status"], "Claim status")))
    add("")
    add(_md_table(_quantiles(claims["claimed_amount"], "Claimed amount (USD)", money=True)))
    add("")
    add(_md_table(_quantiles(claims["reporting_delay_days"], "Reporting delay (days)")))
    add("")

    add("## 7. Known limitations")
    add("")
    for line in [
        "Policies are single-term records; renewals are not modelled.",
        "Claims referred for investigation stay in the REFERRED state; investigation outcomes are not modelled.",
        "A single currency (USD) is used, and names, emails and phone numbers are fictional (example.com addresses).",
        "Claim submission dates are capped at the reference date, so a few claims are bunched on that day.",
        "Fraud-suspected claims (Layer A) are engineered to trip the documented score; real fraud is subtler.",
        "Detection scores for the natural types are circular by construction (see section 5).",
        "Timestamps in the audit log use a synthetic hour-of-day; only the date is meaningful.",
    ]:
        add(f"- {line}")
    add("")
    return "\n".join(out)


def write_report(out_dir, text, clean_results, final_results):
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "validation_summary.md").write_text(text, encoding="utf-8", newline="\n")
    rows = []
    for dataset, results in (("CLEAN", clean_results), ("FINAL", final_results)):
        for r in results:
            rows.append({"dataset": dataset, "check": r["check"], "family": categorize(r["check"]),
                         "passed": r["passed"], "bad_rows": r["bad_rows"]})
    pd.DataFrame(rows).to_csv(out_dir / "validation_results.csv", index=False, lineterminator="\n")